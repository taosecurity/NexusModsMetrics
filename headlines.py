"""Headlines: a few plain-English sentences per Part about the most interesting things in today's data.

The page rebuilds daily, so headlines are generated by rules rather than written by hand. Each rule checks for a
story (a pass, a surge, a type gaining ground...) and returns a sentence only when the data supports it. Rules are
listed in order of interest; each Part shows at most MAX of them.
"""
import datetime
import html

import model

MAX = 5
D = datetime.date


def _e(s):
    return html.escape(str(s))


def short(name):
    return {"The Witcher 3: Wild Hunt": "Witcher 3", "Mount & Blade II: Bannerlord": "Bannerlord",
            "Skyrim Special Edition": "Skyrim SE", "Fallout New Vegas": "New Vegas",
            "Monster Hunter: World": "Monster Hunter: World"}.get(name, name)


def fm(v):
    return f"{v / 1e9:.2f}B" if v >= 1e9 else f"{v / 1e6:.1f}M"


def fi(v):
    return f"{round(v):,}"


def month(d):
    return d.strftime("%B %Y")


def when(dates):
    """'around March 2027 (between January and March 2027)' from (earliest, likely, latest)."""
    e, l, la = dates
    s = f"around <b>{month(l)}</b>"
    if e and la and (e.year, e.month) != (la.year, la.month):
        s += f" (between {e.strftime('%B %Y') if e.year != la.year else e.strftime('%B')} and {month(la)})"
    elif not la:
        s += " (later, or not at all, if the faster pace cools)"
    return s


def day(d):
    return f"{d.day} {d:%B}"


def pc(a, b):
    """Format two percentages so a real difference doesn't round away."""
    digits = 2 if round(a, 1) == round(b, 1) else 1
    return f"{a:.{digits}f}%", f"{b:.{digits}f}%"


def last_crossing(a, b):
    """Most recent date window where series a moved past series b. Returns (before, after) dates or None.
    Uses only dates both series have."""
    db = dict(b)
    common = [(d, v, db[d]) for d, v in a if d in db]
    for i in range(len(common) - 1, 0, -1):
        d0, a0, b0 = common[i - 1]
        d1, a1, b1 = common[i]
        if a0 <= b0 and a1 > b1:
            return d0, d1
    return None


def monthly_new(series):
    """{month_start: new mods in that month} from a cumulative series with 1st-of-month points."""
    firsts = [(d, v) for d, v in series if d.day == 1]
    return {firsts[i][0]: firsts[i + 1][1] - firsts[i][1] for i in range(len(firsts) - 1)}


# ------------------------------------------------------------------ Part 1: downloads
def downloads(data, dl, focus="starfield"):
    rows = {r["domain"]: r for r in dl["rows"]}
    f = rows.get(focus)
    if not f:
        return []
    out = []
    series = data["downloads"]
    name = short(f["name"])

    # 1. the next pass
    ups = sorted((p for p in dl["passes"] if p["dir"] == "up" and p["known"] and p["dates"] and p["dates"][1]),
                 key=lambda p: p["dates"][1])
    if ups:
        p = ups[0]
        out.append((10, f"{name} is on course to pass <b>{_e(short(p['name']))}</b> in downloads {when(p['dates'])}, "
                        f"closing a {fm(p['gap'])} gap at about {(f['speed'][1] - rows[p['domain']]['speed'][1]) / 1e6:.2f}M a day."))

    # 2. a recent pass
    for dom, r in rows.items():
        if dom == focus or dom not in series:
            continue
        c = last_crossing(series[focus], series[dom])
        if c and (D.fromisoformat(f["as_of"]) - c[1]).days <= 120:
            out.append((9, f"{name} recently moved past <b>{_e(short(r['name']))}</b>: it was behind on {day(c[0])} "
                           f"and ahead by {day(c[1])} {c[1].year}, and is now {fm(f['value'] - r['value'])} clear."))

    # 3. fastest grower (by % a month) among games with enough history
    known = [r for r in dl["rows"] if r["speed"] and r["pct_month"] is not None]
    if len(known) >= 3:
        top = max(known, key=lambda r: r["pct_month"])
        others = sorted((r for r in known if r is not top), key=lambda r: -r["pct_month"])
        a, b = pc(top["pct_month"], others[0]["pct_month"] if others else 0)
        lead = (f"<b>{_e(short(top['name']))}</b> is growing fastest of the games with enough history, "
                f"adding {a} a month ({top['speed'][1] / 1e6:.2f}M downloads a day)")
        if others:
            lead += f"; next is {_e(short(others[0]['name']))} at {b}."
        out.append((8, lead))

    # 4. a surge: recent speed well above the 1-year pace
    surges = []
    for r in known:
        s = model.speeds(series.get(r["domain"], []))
        recent = s.get("30") or s.get("90")
        if recent and s.get("365") and s["365"] > 0:
            surges.append((recent / s["365"] - 1, r, "30" if "30" in s else "90"))
    if surges:
        ratio, r, w = max(surges, key=lambda x: x[0])
        if ratio >= 0.25:
            out.append((7, f"<b>{_e(short(r['name']))}</b> is in a growth spurt: its last {w} days ran {ratio * 100:.0f}% "
                           f"above its 1-year pace. If that cools off, {name}'s pass dates come sooner."
                           if r["domain"] != focus else
                           f"<b>{name}</b> is in a growth spurt: its last {w} days ran {ratio * 100:.0f}% above its 1-year pace."))
        slow = min(surges, key=lambda x: x[0])
        if slow[0] <= -0.25:
            out.append((5, f"<b>{_e(short(slow[1]['name']))}</b> is slowing: its last {slow[2]} days ran "
                           f"{-slow[0] * 100:.0f}% below its 1-year pace."))

    # 5. rank outlook
    if f["speed"]:
        r12, r24 = f["proj_rank"][12], f["proj_rank"][24]
        if r24 < f["rank"]:
            est = f["value"] + f["speed"][1] * 730.5
            out.append((6, f"On current trends {name} climbs from <b>#{f['rank']} to #{r24}</b> within two years "
                           f"(about {fm(est)} downloads), with #{r12} likely within 12 months."))

    # 6. threat from behind
    downs = [p for p in dl["passes"] if p["dir"] == "down" and p["known"] and p["dates"] and p["dates"][1]]
    if downs:
        p = min(downs, key=lambda p: p["dates"][1])
        out.append((6, f"Watch your back: <b>{_e(short(p['name']))}</b> is gaining on {name} and could pass it {when(p['dates'])}."))
    elif any(p["dir"] == "down" for p in dl["passes"]):
        p = min((p for p in dl["passes"] if p["dir"] == "down"), key=lambda p: p["gap"])
        out.append((3, f"Nothing behind {name} is catching up; the closest, {_e(short(p['name']))}, is {fm(p['gap'])} back and losing ground."))

    collecting = [r for r in dl["rows"] if not r["speed"]]
    if collecting:
        out.append((1, f"{len(collecting)} of {len(dl['rows'])} games have no download history before daily collection "
                       f"began, so their speeds and pass dates fill in over the next few weeks."))
    return [t for _, t in sorted(out, key=lambda x: -x[0])][:MAX]


# ------------------------------------------------------------------ Part 2: mod count
def mods(data, ma, focus="starfield"):
    rows = {r["domain"]: r for r in ma["rows"]}
    f = rows.get(focus)
    if not f:
        return []
    name = short(f["name"])
    series = data["mods"]
    out = []

    # 1. threat or pass in mod count
    downs = sorted((p for p in ma["passes"] if p["dir"] == "down" and p["known"] and p["dates"] and p["dates"][1]),
                   key=lambda p: p["dates"][1])
    if downs:
        p = downs[0]
        r = rows[p["domain"]]
        ratio = r["speed"][1] / f["speed"][1] if f["speed"] and f["speed"][1] else None
        out.append((10, f"<b>{_e(short(p['name']))}</b> is out-publishing {name}"
                        + (f" about {ratio:.1f} to 1" if ratio and ratio >= 1.5 else "")
                        + f" and could pass it in mod count {when(p['dates'])}."))
    ups = sorted((p for p in ma["passes"] if p["dir"] == "up" and p["known"] and p["dates"] and p["dates"][1]),
                 key=lambda p: p["dates"][1])
    if ups:
        p = ups[0]
        out.append((9, f"With {fi(p['gap'])} mods to go, {name} should pass <b>{_e(short(p['name']))}</b> in mod count {when(p['dates'])}."))

    # 2. Starfield's pace vs a year ago
    mn = monthly_new(series.get(focus, []))
    if len(mn) >= 15:
        ms = sorted(mn)
        recent = sum(mn[m] for m in ms[-3:])
        year_ago = sum(mn[m] for m in ms[-15:-12])
        if year_ago:
            ch = recent / year_ago - 1
            word = "up" if ch > 0 else "down"
            out.append((8, f"Starfield modders published <b>{fi(recent)}</b> mods in {ms[-3]:%B}–{ms[-1]:%B %Y}, "
                           f"{word} {abs(ch) * 100:.0f}% on the same three months a year earlier."))

    # 3. biggest one-month surge across the games
    best = None
    for dom, r in rows.items():
        m = monthly_new(series.get(dom, []))
        if len(m) < 13:
            continue
        ks = sorted(m)
        last, prev = m[ks[-1]], [m[k] for k in ks[-13:-1]]
        avg = sum(prev) / len(prev)
        if avg >= 30 and (best is None or last / avg > best[0]):
            best = (last / avg, r, ks[-1], last, avg)
    if best and best[0] >= 1.8:
        ratio, r, mth, last, avg = best
        out.append((7, f"<b>{_e(short(r['name']))}</b> had a modding burst in {mth:%B %Y}: {fi(last)} new mods, "
                       f"{ratio:.1f}× its usual month ({fi(avg)})."))

    # 4. fastest-growing library
    known = [r for r in ma["rows"] if r["pct_month"] is not None]
    if known:
        top = max(known, key=lambda r: r["pct_month"])
        out.append((6, f"<b>{_e(short(top['name']))}</b> has the fastest-growing mod library, up {top['pct_month']:.1f}% a month "
                       f"(about {fi(top['speed'][1] * 30.44)} new mods a month)."))
        biggest = max(known, key=lambda r: r["speed"][1] if r["speed"] else 0)
        if biggest is not top:
            out.append((4, f"In raw numbers <b>{_e(short(biggest['name']))}</b> still adds the most mods, about "
                           f"{fi(biggest['speed'][1] * 30.44)} a month."))

    # 5. a past pass by Starfield in the last year
    for dom, r in rows.items():
        if dom == focus or dom not in series:
            continue
        c = last_crossing(series[focus], series[dom])
        if c and (D.fromisoformat(f["as_of"]) - c[1]).days <= 365:
            out.append((5, f"{name} passed <b>{_e(short(r['name']))}</b> in mod count in {c[1]:%B %Y}."))
    return [t for _, t in sorted(out, key=lambda x: -x[0])][:MAX]


# ------------------------------------------------------------------ Part 4: top mods
SFSE_WORDS = ("sfse", "script extender", "address library")


def _is_sfse(m):
    n = m["name"].lower()
    return any(w in n for w in SFSE_WORDS)


def top(t):
    """Headlines for Part 4 from data/top_mods.json. Names are escaped here (the page inserts them as HTML)."""
    if not t:
        return []
    out = []
    od, oe = t["overall"]["downloads"], t["overall"]["endorsements"]
    w = t.get("weekly") or {}
    b = w.get("best_loved") or {}
    med = b.get("median_rate")
    rate = lambda m: m["en"] / m["dl"] * 1000 if m["dl"] else 0
    if od and oe:
        a, e = od[0], oe[0]
        lead = f" ({a['dl'] / od[1]['dl']:.1f}× the #2, {_e(od[1]['name'])})" if len(od) > 1 and od[1]["dl"] and a["dl"] >= od[1]["dl"] * 1.5 else ""
        if a["id"] == e["id"]:
            out.append((10, f"<b>{_e(a['name'])}</b> is Starfield's most downloaded and most endorsed mod: {fi(a['dl'])} "
                            f"downloads{lead} and {fi(a['en'])} endorsements."))
        else:
            s = f"Starfield's most downloaded mod is <b>{_e(a['name'])}</b> with {fi(a['dl'])} downloads{lead}"
            if med and rate(a) < med / 4:
                s += (f", but it has only {fi(a['en'])} endorsements ({rate(a):.2f} per 1,000 downloads, against a typical "
                      f"{med:.1f})")
            s += f". The most endorsed is <b>{_e(e['name'])}</b> ({fi(e['en'])} endorsements)."
            out.append((10, s))
    ml = t.get("modlists") or []
    if ml and od and ml[0]["dl"] > od[0]["dl"]:
        m = ml[0]
        out.append((9.5, f"The most downloaded upload of all isn't a single mod: it's the modlist <b>{_e(m['name'])}</b>, "
                         f"with {fm(m['dl'])} downloads against {fm(od[0]['dl'])} for the top mod, but only "
                         f"{fi(m['en'])} endorsements. Part 4 lists modlists with the collections."))
    # Star Wars mods (same name matching as Part 5) in the category top 5s: downloads vs endorsements
    cats = t.get("categories") or []
    if cats:
        from modtypes import SW_RE
        lead = {k: sum(1 for c in cats if c[k] and SW_RE.search(c[k][0]["name"])) for k in ("downloads", "endorsements")}
        slots = {k: sum(1 for c in cats for m in c[k] if SW_RE.search(m["name"])) for k in ("downloads", "endorsements")}
        total = sum(len(c["downloads"]) for c in cats)
        if lead["downloads"] >= 3 and lead["endorsements"] <= lead["downloads"] / 3:
            endo = "none" if lead["endorsements"] == 0 else f"only {lead['endorsements']}"
            out.append((8.8, f"Star Wars mods are the most downloaded mod in <b>{lead['downloads']} of {len(cats)} categories</b>, "
                             f"but the most endorsed in {endo}. They fill {slots['downloads']} of the {total} top-5 places by "
                             f"downloads, but just {slots['endorsements']} by endorsements: widely installed, much less often "
                             f"endorsed."))
    sf = [m for m in oe if _is_sfse(m)]
    if len(sf) >= 2:
        out.append((7, f"{len(sf)} of the 10 most endorsed mods are script-extender tools or need it ("
                       + ", ".join(_e(m["name"]) for m in sf[:3]) + "): Starfield's most valued mods are often the plumbing "
                       f"other mods build on."))
    early = sum(1 for m in oe if m["created"] and m["created"] < "2023-11-01")
    if early >= 7:
        out.append((7.5, f"<b>{'All 10' if early == 10 else f'{early} of the 10'} most endorsed mods</b> came out in Starfield's first two months "
                         f"(by the end of October 2023). Early mods have had the longest to collect endorsements."))
    r = t.get("rising", {}).get("downloads") or []
    if r:
        m = r[0]
        out.append((6, f"The biggest new mod of the last {t['rising']['days']} days is <b>{_e(m['name'])}</b> "
                       f"({_e(m['cat'])}, released {day(D.fromisoformat(m['created']))} {m['created'][:4]}): "
                       f"{fi(m['dl'])} downloads so far."))
    tr = w.get("trending")
    if tr and tr.get("downloads"):
        m = tr["downloads"][0]
        out.append((9, f"Trending this week: <b>{_e(m['name'])}</b> gained the most downloads since {tr['since']} "
                       f"(+{fi(m['g_dl'])})" + (", and it's new this week" if m.get("new") else "") + "."))
    conc = t.get("concentration") or []
    me = next((c for c in conc if c["domain"] == "starfield"), None)
    if me and len(conc) >= 5:
        order = sorted(conc, key=lambda c: -c["top10"] / c["total"])
        rank = order.index(me) + 1
        sh = me["top10"] / me["total"] * 100
        hi, lo = order[0], order[-1]
        where = ("one of the most concentrated" if rank <= 3 else "one of the most spread out" if rank > len(conc) - 3
                 else "middle of the pack")
        s = (f"Starfield's top 10 mods take <b>{sh:.1f}% of its downloads</b>, #{rank} of {len(conc)} games "
             f"({where}). The range runs from {_e(short(hi['name']))} ({hi['top10'] / hi['total'] * 100:.0f}%) "
             f"to {_e(short(lo['name']))} ({lo['top10'] / lo['total'] * 100:.0f}%).")
        alt = me.get("top10_no_modlists")
        if alt and alt < me["top10"]:
            s += f" Counting only ordinary mods (no modlists), Starfield's figure is {alt / me['total'] * 100:.1f}%."
        out.append((6.5, s))
    au = (w.get("authors") or {}).get("downloads") or []
    if au and w.get("downloads_counted"):
        a = au[0]
        out.append((5.5, f"The top author by downloads, <b>{_e(a['name'])}</b>, has {fm(a['dl'])} downloads across "
                         f"{fi(a['mods'])} mods: {a['dl'] / w['downloads_counted'] * 100:.1f}% of all Starfield mod downloads."))
    col = t.get("collections") or {}
    if col.get("downloads") and (ml or od):
        c = col["downloads"][0]
        big = ml[0] if ml else od[0]
        if big["dl"] >= c["dl"] * 20:
            out.append((5, f"Nexus collections are still small for Starfield: the biggest of {fi(col['total'])}, "
                           f"<b>{_e(c['name'])}</b>, has {fi(c['dl'])} downloads, against {fm(big['dl'])} for "
                           + (f"the biggest modlist, {_e(big['name'])}." if ml else "the top mod.")))
    if b.get("top"):
        m = b["top"][0]
        out.append((4, f"The best-loved big mod is <b>{_e(m['name'])}</b>: {m['rate']:.0f} endorsements per 1,000 downloads"
                       + (f", against a typical {med:.1f}" if med else "") + "."))
    return [s for _, s in sorted(out, key=lambda x: -x[0])][:MAX + 2]


# ------------------------------------------------------------------ Part 5: translations and Star Wars
def critics(c):
    if not c:
        return []
    out = []
    tot = c["total"]
    nei = c["neither"] / tot * 100
    tr = c["translation"] / tot * 100
    sw = c["starwars"] / tot * 100
    fr = c["franchise"] / tot * 100
    in_n = round(100 / (100 - nei)) if nei < 100 else None
    out.append((10, f"<b>{nei:.0f}% of Starfield mods</b> ({fi(c['neither'])} of {fi(tot)}) are neither translations nor "
                    f"Star Wars mods" + (f": roughly 4 in 5." if 76 <= nei <= 84 else ".")))
    games = c["games"]
    me = next((g for g in games if g["domain"] == "starfield"), None)
    if me:
        higher = sorted((g for g in games if g["translation"] > me["translation"]), key=lambda g: -g["translation"])
        if higher:
            names = ", ".join(f"{_e(short(g['name']))} ({g['translation']:.0f}%)" for g in higher[:4])
            out.append((9, f"Translations are <b>{tr:.1f}%</b> of Starfield mods, which ranks #{me['translation_rank']} of "
                           f"{len(games)} games. Translation shares are higher for {names}"
                           + (f" and {len(higher) - 4} more" if len(higher) > 4 else "") + "."))
    d = c.get("downloads") or {}
    if d.get("all") and d.get("translation"):
        dsh = d["translation"]["downloads"] / d["all"]["downloads"] * 100
        if dsh < tr * 0.6:
            lead = f"Players rarely download translations: they get only <b>{dsh:.1f}% of Starfield mod downloads</b>"
        elif dsh < tr * 0.9:
            lead = f"Players download translations less: they get <b>{dsh:.1f}% of Starfield mod downloads</b>"
        else:
            lead = f"Translations get <b>{dsh:.1f}% of Starfield mod downloads</b>"
        out.append((8, f"{lead}, against {tr:.1f}% of mods."))
    if d.get("all") and d.get("starwars"):
        ssh = d["starwars"]["downloads"] / d["all"]["downloads"] * 100
        if ssh >= sw * 2:
            out.append((8.5, f"Star Wars mods are few but popular: about <b>{sw:.1f}% of Starfield mods</b> ({fi(c['starwars'])}) "
                             f"but <b>{ssh:.1f}% of downloads</b>, {ssh / sw:.0f}× their share. That's where critics' "
                             f"impression comes from: not volume, but visibility."))
        else:
            out.append((7, f"Mods with Star Wars in the name are about <b>{sw:.1f}% of Starfield mods</b> ({fi(c['starwars'])}) "
                           f"and {ssh:.1f}% of downloads."))
    else:
        out.append((7, f"Mods with Star Wars in the name are about <b>{sw:.1f}% of Starfield mods</b> ({fi(c['starwars'])})."))
    if me:
        rank_word = "the highest" if me["franchise_rank"] == 1 else f"#{me['franchise_rank']}"
        out.append((6, f"Where critics have a point: mods tagged as related to other films, shows, books or games are {fr:.1f}% "
                       f"of Starfield mods, {rank_word} share among the {len(games)} games. That's still about 1 mod in "
                       f"{round(100 / fr)}."))
    if c.get("translation_new90") is not None:
        n90 = c["translation_new90"]
        word = "a smaller" if n90 < tr - 0.5 else "a larger" if n90 > tr + 0.5 else "about the same"
        out.append((4, f"Translations made up {n90:.1f}% of the last 90 days' new Starfield mods, {word} share than "
                       f"their {tr:.1f}% overall."))
    # character presets and saves; AI content
    for key, label, prio in (("presets", "Character presets and save games", 5.5), ("ai", "AI-generated or AI-assisted mods", 5)):
        if c.get(key) is None or not me or key + "_rank" not in me:
            continue
        sh = c[key] / tot * 100
        rank = me[key + "_rank"]
        rank_txt = f"the highest share of the {len(games)} games" if rank == 1 else f"#{rank} of {len(games)} games"
        s = f"{label} are <b>{sh:.1f}%</b> of Starfield mods ({fi(c[key])}), {rank_txt}"
        n90 = c.get(key + "_new90")
        rising = n90 is not None and n90 > sh * 1.5
        if n90 is not None:
            if rising:
                s += f", and rising fast: <b>{n90:.0f}% of the last 90 days' new mods</b>"
            elif n90 > sh * 1.3:
                s += f", and rising: {n90:.1f}% of the last 90 days' new mods"
            elif n90 < sh * 0.7:
                s += f", and falling: {n90:.1f}% of the last 90 days' new mods"
        if d.get("all") and d.get(key):
            dsh = d[key]["downloads"] / d["all"]["downloads"] * 100
            s += (f". But they get only {dsh:.1f}% of downloads" if rank == 1 and dsh < sh * 0.5
                  else f". They get {dsh:.1f}% of downloads")
        if rank == 1:
            s = "Another point for critics: " + s[0].lower() + s[1:]
        out.append((8.2 if rising else prio, s + "."))
    if d.get("all") and d.get("none"):
        nn = d["none"]["mods"] / d["all"]["mods"] * 100
        out.append((9.6, f"Counting all four hot topics together (translations, Star Wars, character presets and saves, AI), "
                         f"<b>{nn:.0f}% of Starfield mods are none of them</b>, and those mods get "
                         f"{d['none']['downloads'] / d['all']['downloads'] * 100:.0f}% of downloads."))
    return [t for _, t in sorted(out, key=lambda x: -x[0])][:MAX + 3]   # Part 5 covers four topics


# ------------------------------------------------------------------ Part 3: mod types
def types(ty):
    if not ty:
        return []
    R = ty["rows"]
    out = []
    gain = [r for r in R if r["new90"] >= 10]
    if gain:
        g = max(gain, key=lambda r: r["trend"])
        if g["trend"] > 1:
            out.append((10, f"<b>{_e(g['name'])}</b> is the type gaining the most ground: {g['share_new90']:.1f}% of the last "
                            f"90 days' new mods, against {g['share']:.1f}% of all Starfield mods."))
    big = [r for r in R if r["mods"] >= 300]
    if big:
        l = min(big, key=lambda r: r["trend"])
        if l["trend"] < -1:
            first = ty["all_lines"].get(l["name"], [])
            tot = ty["all_lines"].get("_total", [])
            hist = ""
            # share at the start of 2024 (once the launch rush settled) vs now, matching the share chart
            for (d, v), (_, tv) in zip(first, tot):
                if d >= "2024-01-01" and tv:
                    hist = f" Its share of all mods has fallen from {v / tv * 100:.0f}% in {D.fromisoformat(d):%B %Y} to {l['share']:.1f}%."
                    break
            out.append((9, f"<b>{_e(l['name'])}</b> is fading: only {l['share_new90']:.1f}% of new mods, against "
                           f"{l['share']:.1f}% of all mods.{hist}"))
    top = R[0] if R else None
    if top and top.get("dl_share") is not None:
        out.append((8, f"<b>{_e(top['name'])}</b> is the biggest type ({top['share']:.1f}% of mods) and also takes "
                       f"{top['dl_share']:.1f}% of all downloads."))
    with_dl = [r for r in R if r.get("dl_share") is not None and r["mods"] >= 100]
    if with_dl:
        over = max(with_dl, key=lambda r: r["dl_share"] / r["share"])
        under = min((r for r in with_dl if r["mods"] >= 300), key=lambda r: r["dl_share"] / r["share"], default=over)
        if over["dl_share"] / over["share"] >= 1.6:
            out.append((7, f"<b>{_e(over['name'])}</b> mods punch above their weight: {over['share']:.1f}% of mods but "
                           f"{over['dl_share']:.1f}% of downloads ({fi(over['avg_dl'])} per mod)."))
        if under["dl_share"] / under["share"] <= 0.65:
            out.append((6, f"<b>{_e(under['name'])}</b> is crowded but less downloaded: {under['share']:.1f}% of mods, "
                           f"only {under['dl_share']:.1f}% of downloads."))
    fast = max(R, key=lambda r: r["new90"]) if R else None
    if fast and fast is not top:
        out.append((5, f"Most new mods in the last 90 days were <b>{_e(fast['name'])}</b> ({fi(fast['new90'])})."))
    games = [g for g in ty.get("games", []) if g["domain"] != "starfield" and g["fastest"]]
    if games:
        g = max(games, key=lambda g: g["new90"])
        out.append((4, f"Across the other games, <b>{_e(short(g['name']))}</b> added the most mods in 90 days "
                       f"({fi(g['new90'])}), led by its <i>{_e(g['fastest'])}</i> category."))
    return [t for _, t in sorted(out, key=lambda x: -x[0])][:MAX]
